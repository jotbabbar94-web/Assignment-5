# BDA400 Assignment 5: reproducible base R checks
for (name in c("sma","ema","macd","stdev","linreg","rsi","stoch_rsi","crossover","crossunder")) source(paste0(name, ".R"))
near <- function(a,b) isTRUE(all.equal(as.numeric(a), as.numeric(b), tolerance=1e-9))
stopifnot(near(sma(c(10,12,15,20), 3), c(37/3,47/3)))
stopifnot(near(ema(c(10,12,14),3), c(10,11,12.5)))
m <- macd(c(100,105,110,115,120,125,130),3,5,2)
stopifnot(length(m$macd_line)==7, near(m$histogram, m$macd_line-m$signal_line))
stopifnot(near(stdev(c(2,4,6)), sqrt(8/3)))
l <- linreg(c(2,4,6,8,10), 3, 1)
stopifnot(near(l$slope,2), near(l$predicted_values,c(4,6,8)))
stopifnot(near(tail(rsi(1:20,5),1),100))
stopifnot(near(tail(rsi(rep(4,20),5),1),50))
s <- stoch_rsi(cumsum(c(100,rep(c(2,-1,3,-2),15))),5,3,3)
stopifnot(length(s$k_line)==61, length(s$d_line)==61)
stopifnot(all(s$k_line[!is.na(s$k_line)] >= 0 & s$k_line[!is.na(s$k_line)] <= 1))
stopifnot(identical(crossover(c(1,3,1),c(2,2,2)), c("None","Up","Down")))
stopifnot(identical(crossunder(c(3,1),c(2,2)), c("None","True")))
cat("All example checks passed. Run these in RStudio and retain console output.\n")
